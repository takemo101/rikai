// 実行できる枠（html-app）の名前と、安全の注意（N3）。DOM・ストアに触れない純粋な関数だけ。
// 注意（「隔離されています。パスワードなどの秘密は、入力しないでください」）は、**見出しに、見える文字としては出さない**（利用者の決定：2026-11-25）。
// 失わないために、見出しの行の `title`（ホバー）・`aria-label`（読み上げ）に持つ（`apps.ts`）。

/** 枠の名前（番号は 1 から）。枠の `title`・範囲の錨の名前（`範囲：実行できる枠 1`）に使う */
export const appName = (n: number): string => `実行できる枠 ${n + 1}`;

/** 安全の注意：枠の中は、隔離されているが、秘密（パスワードなど）は、入力しない */
export const APP_NOTICE = '隔離されています。パスワードなどの秘密は、入力しないでください';

/** 名前＋注意（見出しの行の `title`・`aria-label`） */
export const appNotice = (n: number): string => `${appName(n)}（${APP_NOTICE}）`;

/**
 * 保存済みの範囲の名前（`anchor.label`）から、旧い版が書き込んだ注意を除く（**表示だけ**：保存したデータは、書き換えない）。
 * 旧い版は、見出しの文字から、名前を作った：「範囲：実行できる枠 1（隔離されています。パスワードなどの秘密は、入力しないでください）」・30 字で切った「…（隔離されています。パスワードなどの秘密は…」
 */
export const stripAppNotice = (label: string): string =>
  label.replace(/（隔離されています。パスワードなどの秘密は(?:、入力しないでください）|…)/g, '');
